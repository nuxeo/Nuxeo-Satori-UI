/**
 * Builds the validator the server runs on every write to an app's deployment layer, from
 * `server-validator.ts`, into `nuxeo-agentic-core/src/main/resources/agentic-ui-validator/validator.js`,
 * and the parity corpus the server's run of it is held to.
 *
 *   npm run app-definition:server-validator              # writes both
 *   npm run app-definition:server-validator -- --check   # exits 1 if either differs
 *
 * The command line is `server-validator-bin.mjs`; this file only builds, so that the spec can too.
 *
 * The server's JavaScript engine is the one Nuxeo LTS 2025 ships, Nashorn 15.7, in `nxserver/lib`
 * (`nuxeo-agentic-assets/README.md` records reading it there), run with `--language=es6`. That has
 * `let`, `const`, arrow functions, template literals, `for...of`, `Map`, `Set` and `Symbol`, and not
 * classes, spread, destructuring or the library methods after ES2015. So the script is built in two
 * steps, each a tool the repository already pins:
 *
 * 1. esbuild bundles the TypeScript into one script, for ES2015, which lowers optional chaining,
 *    `??`, object spread and the rest of what came after;
 * 2. TypeScript lowers that to ES5, with `downlevelIteration`, so that spread and destructuring go
 *    through `Symbol.iterator`, which Nashorn has.
 *
 * A prelude adds the library methods the validator calls that Nashorn lacks, each only where it is
 * missing. What it covers is held by the parity check, not by this list: the server's run of the
 * parity corpus, `nuxeo-agentic-core/src/test/resources/agentic-ui-validator/parity.json`, must give
 * the answers this source gives (`DeploymentValidatorParityTest`). This file writes the corpus too,
 * and `server-validator.spec.ts` checks that both files are what the source builds now.
 *
 * The output is the same bytes on every system: esbuild and TypeScript are pinned by the lockfile,
 * paths are relative to the repository, and the text is ASCII with LF line ends.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO = resolve(HERE, '..', '..', '..', '..');
export const ENTRY = join(HERE, 'server-validator.ts');
export const OUTPUT = join(
  REPO,
  'nuxeo-agentic-core',
  'src',
  'main',
  'resources',
  'agentic-ui-validator',
  'validator.js',
);

/** The name the script gives its entry points, a global Nashorn reads them from. */
export const GLOBAL_NAME = 'agenticUiValidator';

const HEADER = `/*
 * GENERATED by libs/shared/app-definition/src/server-validator-build.mjs from
 * libs/shared/app-definition/src/server-validator.ts. Do not edit: run
 * \`npm run app-definition:server-validator\` and commit the result.
 *
 * The app definition's validator, as nuxeo-agentic-core runs it in Nashorn on every write to a
 * deployment layer (DeploymentValidator). ES5, for Nashorn 15.7 with --language=es6.
 */
`;

/**
 * The library methods the validator calls that Nashorn 15.7 lacks, defined only where missing, so
 * that an engine that has them keeps its own. Each follows the specification for what the
 * validator passes it; none is a general polyfill.
 */
const PRELUDE = `(function () {
  'use strict';
  function define(target, name, value) {
    if (typeof target[name] !== 'function') {
      Object.defineProperty(target, name, { value: value, configurable: true, writable: true, enumerable: false });
    }
  }
  var hasOwn = Object.prototype.hasOwnProperty;
  define(Object, 'hasOwn', function (object, key) { return hasOwn.call(Object(object), key); });
  define(Object, 'getOwnPropertyDescriptors', function (object) {
    var result = {};
    var names = Object.getOwnPropertyNames(object);
    for (var index = 0; index < names.length; index++) result[names[index]] = Object.getOwnPropertyDescriptor(object, names[index]);
    if (typeof Object.getOwnPropertySymbols === 'function') {
      var symbols = Object.getOwnPropertySymbols(object);
      for (var inner = 0; inner < symbols.length; inner++) result[symbols[inner]] = Object.getOwnPropertyDescriptor(object, symbols[inner]);
    }
    return result;
  });
  define(Object, 'entries', function (object) {
    var result = [];
    for (var key in object) if (hasOwn.call(object, key)) result.push([key, object[key]]);
    return result;
  });
  define(Object, 'values', function (object) {
    var result = [];
    for (var key in object) if (hasOwn.call(object, key)) result.push(object[key]);
    return result;
  });
  define(Object, 'assign', function (target) {
    for (var index = 1; index < arguments.length; index++) {
      var source = arguments[index];
      if (source == null) continue;
      for (var key in source) if (hasOwn.call(source, key)) target[key] = source[key];
    }
    return target;
  });
  define(Object, 'fromEntries', function (entries) {
    var result = {};
    var iterator = entries[Symbol.iterator]();
    for (var step = iterator.next(); !step.done; step = iterator.next()) result[step.value[0]] = step.value[1];
    return result;
  });
  define(Array, 'from', function (items, mapper) {
    var result = [];
    if (items != null && typeof items[Symbol.iterator] === 'function') {
      var iterator = items[Symbol.iterator]();
      for (var step = iterator.next(); !step.done; step = iterator.next()) result.push(step.value);
    } else {
      for (var index = 0; index < items.length; index++) result.push(items[index]);
    }
    return mapper ? result.map(mapper) : result;
  });
  define(Array.prototype, 'includes', function (value) {
    for (var index = 0; index < this.length; index++) {
      var item = this[index];
      if (item === value || (item !== item && value !== value)) return true;
    }
    return false;
  });
  define(Array.prototype, 'find', function (test) {
    for (var index = 0; index < this.length; index++) if (test(this[index], index, this)) return this[index];
    return undefined;
  });
  define(Array.prototype, 'findIndex', function (test) {
    for (var index = 0; index < this.length; index++) if (test(this[index], index, this)) return index;
    return -1;
  });
  define(Array.prototype, 'flatMap', function (mapper) {
    var result = [];
    for (var index = 0; index < this.length; index++) {
      var mapped = mapper(this[index], index, this);
      if (Array.isArray(mapped)) for (var inner = 0; inner < mapped.length; inner++) result.push(mapped[inner]);
      else result.push(mapped);
    }
    return result;
  });
  define(String.prototype, 'matchAll', function (pattern) {
    var flags = typeof pattern.flags === 'string' ? pattern.flags
      : (pattern.global ? 'g' : '') + (pattern.ignoreCase ? 'i' : '') + (pattern.multiline ? 'm' : '');
    if (flags.indexOf('g') === -1) throw new TypeError('matchAll is called with a global RegExp');
    var matcher = new RegExp(pattern.source, flags);
    var text = String(this);
    var done = false;
    var iterator = {
      next: function () {
        if (done) return { value: undefined, done: true };
        var match = matcher.exec(text);
        if (match === null) { done = true; return { value: undefined, done: true }; }
        if (match[0] === '') matcher.lastIndex++;
        return { value: match, done: false };
      }
    };
    iterator[Symbol.iterator] = function () { return this; };
    return iterator;
  });
  define(String.prototype, 'includes', function (text, from) { return this.indexOf(text, from || 0) !== -1; });
  define(String.prototype, 'startsWith', function (text, from) { var at = from || 0; return this.substr(at, text.length) === text; });
  define(String.prototype, 'endsWith', function (text) { return this.length >= text.length && this.slice(this.length - text.length) === text; });
  define(String, 'raw', function (strings) {
    var raw = strings.raw;
    var result = '';
    for (var index = 0; index < raw.length; index++) {
      result += raw[index];
      if (index + 1 < raw.length && index + 1 < arguments.length) result += String(arguments[index + 1]);
    }
    return result;
  });
  define(Number, 'isInteger', function (value) { return typeof value === 'number' && isFinite(value) && Math.floor(value) === value; });
  define(Number, 'isSafeInteger', function (value) { return Number.isInteger(value) && Math.abs(value) <= 9007199254740991; });
  define(Number, 'isFinite', function (value) { return typeof value === 'number' && isFinite(value); });
})();
`;

/** The script, as it is built from the source now. */
export async function buildServerValidator() {
  const [{ buildSync }, ts] = await Promise.all([import('esbuild'), import('typescript')]);
  const bundled = buildSync({
    entryPoints: [relative(REPO, ENTRY)],
    absWorkingDir: REPO,
    bundle: true,
    write: false,
    format: 'iife',
    globalName: GLOBAL_NAME,
    platform: 'neutral',
    target: 'es2015',
    charset: 'ascii',
    legalComments: 'none',
    logLevel: 'silent',
  });
  const es2015 = bundled.outputFiles[0].text;
  const es5 = (ts.default ?? ts).transpileModule(es2015, {
    compilerOptions: {
      target: (ts.default ?? ts).ScriptTarget.ES5,
      module: (ts.default ?? ts).ModuleKind.None,
      downlevelIteration: true,
      newLine: (ts.default ?? ts).NewLineKind.LineFeed,
      removeComments: false,
    },
    reportDiagnostics: false,
  }).outputText;
  return `${HEADER}${PRELUDE}${es5.replace(/\r\n/g, '\n')}`;
}

/** Where the parity corpus is: the files, the findings this source gives them, for the server's test. */
export const PARITY = join(
  REPO,
  'nuxeo-agentic-core',
  'src',
  'test',
  'resources',
  'agentic-ui-validator',
  'parity.json',
);

const KITS = join(REPO, 'business-apps', 'packages');
const KIT_NAMES = ['brand-assets-demo', 'contracts-demo', 'facilities-demo', 'payers-claims-demo'];

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const optionalJson = (path) => (existsSync(path) ? readJson(path) : null);

/** A rule nested `depth` deep: past the validator's limit, it is a `parameter` finding. */
function nested(depth) {
  let rule = 'app.rules.canWrite';
  for (let level = 0; level < depth; level++) rule = { type: 'core.not', parameters: { rule } };
  return rule;
}

/** The layout files of a record page, an edit or a create form, and the queues, in a kit's folder. */
function kitFiles(root) {
  const under = (folder) =>
    existsSync(join(root, folder)) ? readdirSync(join(root, folder)).sort() : [];
  const layouts = under('layouts').flatMap((type) =>
    readdirSync(join(root, 'layouts', type))
      .sort()
      .filter((file) => /^(view|edit|create)\.layout\.json$/.test(file))
      .map((file) => `layouts/${type}/${file}`),
  );
  const queues = under('queues')
    .filter((file) => file.endsWith('.json'))
    .map((file) => `queues/${file}`);
  return { layouts, queues };
}

/** A kit's first layout, broken in the ways a designer's draft could be, and its first queue. */
function brokenCases(root, layout, queue, add) {
  if (layout) {
    const content = readJson(join(root, layout));
    const broken = (label, change) => {
      const copy = structuredClone(content);
      change(copy);
      add(`${layout}, ${label}`, { path: layout, content: copy });
    };
    broken('a key version 2 does not have', (file) => {
      file.bogus = true;
    });
    broken('version 1', (file) => {
      file.version = 1;
    });
    broken('a property the type does not have', (file) => {
      const cards = file.cards ?? file.tabs?.[0]?.cards ?? [];
      const card = cards.find((each) => Array.isArray(each.fields));
      if (card) card.fields.push('zz:nope');
      else file.cards = [{ id: 'added', fields: ['zz:nope'] }];
    });
    broken('a widget nobody registered', (file) => {
      file.cards = [{ id: 'added', fields: [{ field: 'dc:title', widget: 'acme.unregistered' }] }];
    });
    broken('a rule nobody registered', (file) => {
      file.cards = [{ id: 'added', visibleWhen: 'acme.rules.custom', fields: ['dc:title'] }];
    });
    broken('a label that is markup', (file) => {
      file.cards = [{ id: 'added', label: '<img src=x onerror=alert(1)>', fields: ['dc:title'] }];
    });
    broken('a template naming what is no property', (file) => {
      file.cards = [
        {
          id: 'added',
          fields: [
            {
              id: 'named',
              computed: { type: 'core.template', parameters: ['{dc:title} {nope} {zz:none} {}'] },
            },
          ],
        },
      ];
    });
    broken('a rule nested deeper than the validator reads', (file) => {
      file.cards = [{ id: 'added', visibleWhen: nested(300), fields: ['dc:title'] }];
    });
    add(`${layout}, not an object`, { path: layout, content: [] });
    add(`${layout}, null`, { path: layout, content: null });
    const minimal = { version: 2, cards: [{ id: 'added', visibleWhen: 'acme.rules.custom', fields: ['dc:title'] }] };
    add(`${layout}, a rule the deployment registers`, {
      path: layout,
      content: minimal,
      registered: { rules: ['acme.rules.custom'] },
    });
    const type = layout.split('/')[1];
    add(`layouts/${type}/create.layout.json, a create form`, {
      path: `layouts/${type}/create.layout.json`,
      content: {
        version: 2,
        cards: [{ id: 'main', fields: ['dc:title', { field: 'dc:description', required: true }] }],
      },
    });
    add(`layouts/${type}/metadata.layout.json, a mode no layer holds`, {
      path: `layouts/${type}/metadata.layout.json`,
      content,
    });
  }
  if (queue) {
    const content = readJson(join(root, queue));
    add(`${queue}, without the app's actions`, { path: queue, content, noActions: true });
    const unknown = structuredClone(content);
    unknown.bogus = true;
    add(`${queue}, a key a queue does not have`, { path: queue, content: unknown });
    const withoutProvider = structuredClone(content);
    delete withoutProvider.pageProvider;
    add(`${queue}, no page provider`, { path: queue, content: withoutProvider });
  }
}

/**
 * The files the server's run of the validator is held to: every layout file of a record page, an
 * edit or a create form, and every queue, of each starter kit, with its own content model and
 * actions; each kit's first layout and first queue broken in the ways a designer's draft could be;
 * and the paths and the model the server refuses outright.
 */
function parityCases() {
  const kits = {};
  const cases = [];
  for (const name of KIT_NAMES) {
    const root = join(KITS, name, 'bundle', 'agentic-ui-config');
    kits[name] = {
      model: readJson(join(KITS, name, 'content-model.json')),
      app: optionalJson(join(root, 'app.json')),
      actions: optionalJson(join(root, 'actions.json')),
    };
    const add = (label, request) => cases.push({ name: `${name}: ${label}`, kit: name, request });
    const { layouts, queues } = kitFiles(root);
    for (const path of [...layouts, ...queues]) add(path, { path, content: readJson(join(root, path)) });
    brokenCases(root, layouts[0], queues[0], add);
  }
  const kit = KIT_NAMES[0];
  const empty = { version: 2, cards: [] };
  cases.push(
    { name: 'home.json, a file no layer holds', kit, request: { path: 'home.json', content: {} } },
    { name: 'labels/en.json, a file no layer holds', kit, request: { path: 'labels/en.json', content: {} } },
    { name: 'app.json, a file no layer holds', kit, request: { path: 'app.json', content: {} } },
    {
      name: 'a layout below another folder',
      kit,
      request: { path: 'x/layouts/Note/view.layout.json', content: empty },
    },
    {
      name: 'a model that cannot be read',
      kit,
      request: { path: 'layouts/Note/view.layout.json', content: empty, model: {} },
    },
  );
  return { kits, cases };
}

/**
 * The parity corpus as JSON text: each case, the kit whose model, `app.json` and `actions.json` it
 * is asked with, and the answer this source gives it.
 *
 * @param validate `validateDeploymentFile` from `server-validator.ts`
 */
export function buildParityCorpus(validate) {
  const { kits, cases } = parityCases();
  const written = cases.map(({ name, kit, request }) => {
    const { noActions, ...asked } = request;
    const full = {
      model: kits[kit].model,
      app: kits[kit].app,
      actions: noActions ? null : kits[kit].actions,
      ...asked,
    };
    return {
      name,
      kit,
      ...asked,
      noActions: noActions === true,
      expected: JSON.parse(JSON.stringify(validate(full))),
    };
  });
  const comment =
    'GENERATED by libs/shared/app-definition/src/server-validator-build.mjs: run npm run app-definition:server-validator. DeploymentValidatorParityTest asks the server validator each case, with its kit model (or its own), app.json and actions.json (none when noActions), and the answer must be expected, the answer server-validator.ts gives here.';
  // One kit and one case to a line: a case nested 300 deep would be megabytes indented.
  const lines = (entries) => entries.join(',\n');
  return (
    `{\n"$comment": ${JSON.stringify(comment)},\n"kits": {\n` +
    lines(Object.entries(kits).map(([name, kit]) => `${JSON.stringify(name)}: ${JSON.stringify(kit)}`)) +
    `\n},\n"cases": [\n${lines(written.map((each) => JSON.stringify(each)))}\n]\n}\n`
  );
}

/**
 * Both files as the source builds them now.
 *
 * @param validate `validateDeploymentFile` from `server-validator.ts`
 */
export async function buildOutputs(validate) {
  return [
    { path: OUTPUT, text: await buildServerValidator() },
    { path: PARITY, text: buildParityCorpus(validate) },
  ];
}

/** Those of the outputs that the files on disk do not hold. */
export function outOfDate(outputs) {
  return outputs.filter(({ path, text }) => {
    try {
      return readFileSync(path, 'utf8') !== text;
    } catch {
      return true;
    }
  });
}
