#!/usr/bin/env node
/**
 * Compile the Nx generators into the platform package, so customers actually receive them.
 *
 * ## The gap this closes
 *
 * `libs/platform/AGENTS.md` — the customer-facing guide, shipped inside the tarball —
 * opens section 2 with:
 *
 *     npx nx g ./tools/satori-generators:extension-library acme-extensions --owner=acme
 *
 * `./tools/satori-generators` is a path in **our** repository. A customer who installs
 * `@nuxeo-satori/platform` has no such directory, so the very first instruction in the
 * guide could not be run by its audience. Layer 3 — "the differentiator", per the plan —
 * was documented and not distributed.
 *
 * With this, the generators ship at the package root and the command becomes
 *
 *     npx nx g @nuxeo-satori/platform:extension-library acme-extensions --owner=acme
 *
 * which is what an Nx plugin consumer expects: `generators.json` at the package root,
 * named in `package.json`.
 *
 * ## Why a copy step rather than an ng-packagr asset path
 *
 * Same reason as `sync-platform-docs.mjs`: ng-packagr refuses assets from outside the
 * package root ("Cannot read assets from a location outside of the project root"). So the
 * compiled output is written *into* `libs/platform/`, gitignored, and picked up as an
 * asset. It must be produced BEFORE `nx build platform`, because ng-packagr clears its
 * destination — writing into `dist/` afterwards would work until the next cache hit.
 *
 * ## Why CommonJS
 *
 * Nx `require()`s a generator factory. The sources are TypeScript with `import`
 * statements; emitting ESM would make them unloadable by the tool that runs them.
 *
 * Usage:
 *   node scripts/build-platform-generators.mjs           # compile + copy
 *   node scripts/build-platform-generators.mjs --check   # verify the output is current
 */

import { execFileSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const SRC = join(ROOT, 'tools/satori-generators');
const OUT = join(ROOT, 'libs/platform/generators');
const MANIFEST = join(ROOT, 'libs/platform/generators.json');
const check = process.argv.includes('--check');

const BANNER =
  '// GENERATED by scripts/build-platform-generators.mjs from tools/satori-generators.\n' +
  '// Do not edit: this file is gitignored and overwritten on every platform build.\n';

/** Every non-TypeScript file a generator reads at run time: schemas and templates. */
function assets(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) assets(full, out);
    else if (!full.endsWith('.ts')) out.push(relative(join(SRC, 'src'), full));
  }
  return out;
}

if (!existsSync(join(SRC, 'generators.json'))) {
  console.error(`build-platform-generators: ${SRC}/generators.json is missing.`);
  process.exit(1);
}

const previous = check && existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : null;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// tsc, invoked with flags rather than a tsconfig file: the whole configuration is four
// options and a tsconfig would be a fifth file to keep in step with this one.
// Run tsc's own entry script with this Node, not `npx`: `npx` is `npx.cmd` on Windows, which
// Node only starts through a shell, and a shell re-splits any argument containing a space —
// every path below, in a checkout under a directory such as `C:\work\Agentic UI`.
const TSC = createRequire(import.meta.url).resolve('typescript/bin/tsc');
try {
  execFileSync(
    process.execPath,
    [
      TSC,
      '--outDir',
      OUT,
      '--rootDir',
      join(SRC, 'src'),
      '--module',
      'commonjs',
      '--moduleResolution',
      'node',
      '--target',
      'es2022',
      '--declaration',
      'false',
      '--sourceMap',
      'false',
      '--skipLibCheck',
      'true',
      '--strict',
      'true',
      '--esModuleInterop',
      'true',
      ...readdirSync(join(SRC, 'src'), { recursive: true })
        // Specs run in this repository only; they would not compile without vitest's types.
        .filter((f) => typeof f === 'string' && f.endsWith('.ts') && !f.endsWith('.spec.ts'))
        .map((f) => join(SRC, 'src', f)),
    ],
    {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    },
  );
} catch (error) {
  console.error(
    'build-platform-generators: tsc failed.\n' + `${error.stdout ?? ''}${error.stderr ?? ''}`,
  );
  process.exit(1);
}

for (const asset of assets(join(SRC, 'src'))) {
  const target = join(OUT, asset);
  mkdirSync(resolve(target, '..'), { recursive: true });
  cpSync(join(SRC, 'src', asset), target);
}

/**
 * The manifest, with every factory and schema path rewritten to the shipped layout.
 *
 * Rewritten rather than hand-maintained: `./src/extension-rule/generator` in the source
 * manifest becomes `./generators/extension-rule/generator`, and a second hand-written copy
 * would drift from the first the moment a generator is added.
 */
const manifest = JSON.parse(readFileSync(join(SRC, 'generators.json'), 'utf8'));
// `x-satori-internal` generators add to the platform's own source — `satori-component` writes
// `nxs-` components into `libs/shared/satori-components` — so a customer's workspace has nothing
// for them to act on, and they are not shipped. Their compiled output is removed below too.
const internal = Object.entries(manifest.generators ?? {})
  .filter(([, generator]) => generator['x-satori-internal'] === true)
  .map(([name]) => name);
for (const name of internal) {
  delete manifest.generators[name];
  rmSync(join(OUT, name), { recursive: true, force: true });
}
for (const generator of Object.values(manifest.generators ?? {})) {
  for (const key of ['factory', 'schema']) {
    if (typeof generator[key] === 'string') {
      generator[key] = generator[key].replace(/^\.\/src\//, './generators/');
    }
  }
}
const rendered = `${JSON.stringify(manifest, null, 2)}\n`;

if (check) {
  if (previous !== rendered) {
    console.error(
      'build-platform-generators: libs/platform/generators.json is stale.\n' +
        '  Run `node scripts/build-platform-generators.mjs`.',
    );
    process.exit(1);
  }
}
writeFileSync(MANIFEST, rendered);

// A README beside the compiled output, so a customer who opens the directory is not left
// guessing whether it is theirs to edit.
writeFileSync(
  join(OUT, 'README.md'),
  `${BANNER.replace(/^\/\/ ?/gm, '')}\nRun them with:\n\n` +
    '```bash\n' +
    'npx nx g @nuxeo-satori/platform:extension-library acme-extensions --owner=acme\n' +
    '```\n\nSource: `tools/satori-generators` in the platform repository.\n',
);

const names = Object.keys(manifest.generators ?? {});
console.log(
  `build-platform-generators: ${names.length} generator(s) -> libs/platform/generators/ ` +
    `(${names.join(', ')})`,
);
