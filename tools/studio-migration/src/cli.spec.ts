import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { main, type CliIo } from './cli';
import { syntheticBundleFiles, syntheticPackage } from './testing/synthetic-package';

const UI = 'web/nuxeo.war/ui';
const syntheticPackageFile = (path: string): string => syntheticBundleFiles()[path];

function run(
  argv: string[],
  files: Record<string, Buffer> = {},
): { code: number; out: string; err: string } {
  let out = '';
  let err = '';
  const io: CliIo = {
    out: (text) => (out += text),
    err: (text) => (err += text),
    readFile: (path) => {
      if (path in files) return files[path];
      throw Object.assign(new Error(`ENOENT: no such file, open '${path}'`), { code: 'ENOENT' });
    },
  };
  return { code: main(argv, io), out, err };
}

describe('studio-migration inventory', () => {
  it('prints what the package holds and where each part goes, and exits 0', () => {
    const { code, out, err } = run(['inventory', 'acme.zip'], { 'acme.zip': syntheticPackage() });
    expect(code).toBe(0);
    expect(err).toBe('');
    expect(out).toContain(
      'Acme-Claims 1.0.0: a studio package for [2025.0,2026) (lts), depending on nuxeo-web-ui',
    );
    expect(out).toContain(
      'Document layouts: 3\n  Claim: view (5 fields), edit (3 fields), metadata (3 fields)',
    );
    expect(out).toContain(
      'claims: a form with 2 fields; results with 3 columns, shown as nuxeo-data-table',
    );
    expect(out).toMatch(/DOCUMENT_ACTIONS +approveClaim +automatic → toolbar/);
    expect(out).toMatch(/THEMES +acme +automatic → Layer 0 themes/);
    expect(out).toContain('Dashboard: 3 cards, 1 of them a repeat');
    expect(out).toContain('Theme acme: 5 properties, 2 set a token and 3 are reported');
    expect(out).toContain('Translations: en 3 keys, fr 3 keys');
    expect(out).toContain('Scripts: 5, 5 of them generated by Studio or Web UI');
    expect(out).toContain('Conditions: 5, converted in M2 with truth tables');
    expect(out).toContain(
      'Decisions needed: 2\n' +
        '  - theme acme: 3 of its 5 properties set no token and are reported\n' +
        '  - dashboard card 2 (Open claims) repeats card 1, and is kept once',
    );
  });

  it('lists what the catalogue reports or leaves for an agent, not only what it does not know', () => {
    const pkg = syntheticPackage({
      bundle: {
        [`${UI}/nuxeo-Acme-Claims-bundle.html`]: `
          <nuxeo-slot-content name="report" slot="PAGES"><template><nuxeo-card></nuxeo-card></template></nuxeo-slot-content>
          <nuxeo-slot-content name="me" slot="USER_MENU"><template><nuxeo-operation op="Favorite.Fetch"></nuxeo-operation></template></nuxeo-slot-content>`,
        [`${UI}/nuxeo-Acme-Claims-custom-bundle.html`]:
          '<script>Polymer({ is: "acme-x" })</script>',
      },
    });
    const { out } = run(['inventory', 'acme.zip'], { 'acme.zip': pkg });
    expect(out).toMatch(
      /slot PAGES \(contribution "report"\) is for an agent to propose: A page is a custom element/,
    );
    expect(out).toMatch(
      /slot USER_MENU \(contribution "me"\) is reported: The app has no slot for it yet/,
    );
    expect(out).toMatch(
      /element nuxeo-operation \(used once\) is for an agent to propose: Home cards read page providers/,
    );
    expect(out).toContain(
      `${UI}/nuxeo-Acme-Claims-custom-bundle.html holds customer code, for an agent to propose as a Layer 2 plugin`,
    );
  });

  it('lists a script that is not one Studio generates as customer code to review', () => {
    const path = `${UI}/document/claim/nuxeo-claim-view-layout.html`;
    const original = syntheticPackageFile(path);
    const pkg = syntheticPackage({
      bundle: {
        [path]: original.replace('behaviors:', 'ready: function() { this.track(); }, behaviors:'),
      },
    });
    const { out } = run(['inventory', 'acme.zip'], { 'acme.zip': pkg });
    expect(out).toContain('Scripts: 5, 4 of them generated by Studio or Web UI, 1 not');
    expect(out).toContain(
      `script 1 in ${path} is not one Studio generates: review it as customer code`,
    );
  });

  it('does not take a slot named after an Object property for a known one', () => {
    const pkg = syntheticPackage({
      bundle: {
        [`${UI}/nuxeo-Acme-Claims-bundle.html`]:
          '<nuxeo-slot-content name="x" slot="constructor"><template></template></nuxeo-slot-content>',
      },
    });
    const { out } = run(['inventory', 'acme.zip'], { 'acme.zip': pkg });
    expect(out).toMatch(/constructor +x +not in the catalogue/);
    expect(out).toContain('slot constructor (contribution "x") is not in the catalogue');
  });

  it('reports the mistakes a real project carries: a button with no operation, a field bound twice', () => {
    const pkg = syntheticPackage({
      bundle: {
        [`${UI}/nuxeo-Acme-Claims-bundle.html`]:
          '<nuxeo-slot-content name="TestBtn" slot="DOCUMENT_ACTIONS"><template><nuxeo-operation-button label="Test"></nuxeo-operation-button></template></nuxeo-slot-content>',
        [`${UI}/document/claim/nuxeo-claim-import-layout.html`]: `<dom-module id="nuxeo-claim-import-layout"><template>
          <nuxeo-input role="widget" value="{{document.properties.dc:title}}" label="Title"></nuxeo-input>
          <nuxeo-input role="widget" value="{{document.properties.dc:description}}" label="Description"></nuxeo-input>
          <nuxeo-input role="widget" value="{{document.properties.dc:title}}" label="Title"></nuxeo-input>
        </template></dom-module>`,
      },
    });
    const { out } = run(['inventory', 'acme.zip'], { 'acme.zip': pkg });
    expect(out).toContain(
      'slot DOCUMENT_ACTIONS (contribution "TestBtn") has a nuxeo-operation-button that runs no operation',
    );
    expect(out).toContain(
      'layout nuxeo-claim-import-layout binds dc:title 2 times, and keeps it once',
    );
  });

  it('lists what the catalogue cannot place as decisions, rather than passing it', () => {
    const pkg = syntheticPackage({
      bundle: {
        [`${UI}/nuxeo-Acme-Claims-bundle.html`]:
          '<nuxeo-slot-content name="x" slot="MY_SLOT"><template><acme-widget></acme-widget></template></nuxeo-slot-content>',
        [`${UI}/mystery/review/nuxeo-review-panel.html`]: '<p></p>',
      },
    });
    const { code, out } = run(['inventory', 'acme.zip'], { 'acme.zip': pkg });
    expect(code).toBe(0);
    // The three below, the theme's reported properties and the repeated dashboard card.
    expect(out).toContain('Decisions needed: 5');
    expect(out).toContain('slot MY_SLOT (contribution "x") is not in the catalogue');
    expect(out).toContain('element acme-widget (used once) is not in the catalogue');
    expect(out).toContain(`file ${UI}/mystery/review/nuxeo-review-panel.html is of no known kind`);
  });

  it('writes the whole inventory and accounting as JSON with --json', () => {
    const { code, out } = run(['inventory', 'acme.zip', '--json'], {
      'acme.zip': syntheticPackage(),
    });
    expect(code).toBe(0);
    const parsed = JSON.parse(out);
    expect(parsed.inventory.descriptor.name).toBe('Acme-Claims');
    expect(parsed.inventory.elements['nuxeo-input']).toBe(2);
    expect(parsed.accounting.decisions).toEqual([
      'theme acme: 3 of its 5 properties set no token and are reported',
      'dashboard card 2 (Open claims) repeats card 1, and is kept once',
    ]);
  });

  it('exits 1 with the reason when the package cannot be read', () => {
    const notAPackage = run(['inventory', 'bad.zip'], {
      'bad.zip': Buffer.from('not a zip archive at all, but long'),
    });
    expect(notAPackage.code).toBe(1);
    expect(notAPackage.err).toMatch(/^bad\.zip: not a ZIP archive/);
    expect(notAPackage.out).toBe('');

    const missing = run(['inventory', 'missing.zip']);
    expect(missing.code).toBe(1);
    expect(missing.err).toMatch(/^missing\.zip: ENOENT/);
  });

  it('exits 2 for a command it does not know, a missing or extra path, or an unknown option', () => {
    for (const argv of [
      [],
      ['convert', 'a.zip'],
      ['inventory'],
      ['inventory', 'a.zip', 'b.zip'],
      ['inventory', 'a.zip', '--yaml'],
    ]) {
      const { code, err } = run(argv);
      expect(code).toBe(2);
      expect(err).toMatch(/^usage:/);
    }
  });
});

describe('studio-migration convert, check and mutate', () => {
  const files = {
    'acme.zip': syntheticPackage(),
    'allow.json': Buffer.from(JSON.stringify({ operations: ['Claim.Approve'] })),
  };
  const fresh = () => join(mkdtempSync(join(tmpdir(), 'studio-cli-')), 'conversion');

  it('converts, and the harness passes what runs without a server while saying the migration is not ready', () => {
    const out = fresh();
    const converted = run(['convert', 'acme.zip', out, '--allow-list', 'allow.json'], files);
    expect(converted.code).toBe(0);
    expect(converted.out).toMatch(/^Converted Acme-Claims 1\.0\.0 into /);
    expect(converted.out).toContain(
      'app/: 11 files: app.json, 3 layouts, 2 queues, home.json, navigation.json, actions.json, 2 labels files',
    );
    expect(converted.out).toContain('labels: en (3), fr (3)');
    expect(converted.out).toContain('themes: acme (2 tokens, 1 file)');

    const checked = run(['check', 'acme.zip', out, '--allow-list', 'allow.json'], files);
    expect(checked.code).toBe(0);
    for (const [number, name] of [
      [1, 'Nothing dropped'],
      [2, 'Fields'],
      [4, 'Labels'],
      [8, 'Theme'],
      [10, 'Package'],
    ])
      expect(checked.out).toMatch(new RegExp(` ?${number} {2}${name} +pass`));
    expect(checked.out).toMatch(/ 3 {2}Model +partial: 1 name rests on the platform's own model/);
    expect(checked.out).toMatch(/ 7 {2}What the server is asked +partial: /);
    expect(checked.out).toContain('  - check 6 ran only in part');
    expect(checked.out).toContain('Verdict: not ready');
  });

  it('checks actions against the allow-list it is given, or else the one the conversion was made with', () => {
    const out = fresh();
    run(['convert', 'acme.zip', out, '--allow-list', 'allow.json'], files);
    const recorded = run(['check', 'acme.zip', out], files);
    expect(recorded.code).toBe(0);
    expect(recorded.out).toMatch(
      /10 {2}Package +partial: .*the allow-list the conversion recorded/,
    );
    const none = { ...files, 'none.json': Buffer.from('{"operations": []}') };
    const refused = run(['check', 'acme.zip', out, '--allow-list', 'none.json'], none);
    expect(refused.code).toBe(1);
    expect(refused.out).toMatch(/10 {2}Package +FAIL/);
    expect(refused.out).toContain('Claim.Approve');

    const without = fresh();
    run(['convert', 'acme.zip', without], files);
    const reported = JSON.parse(readFileSync(join(without, 'report.json'), 'utf8'));
    expect(
      reported.constructs.find((entry: { label: string }) => entry.label.includes('approveClaim')),
    ).toMatchObject({
      outcome: 'reported',
      note: expect.stringMatching(/not on the deployment's allow-list/),
    });
  });

  it('refuses an allow-list that is not one', () => {
    const bad = { ...files, 'bad.json': Buffer.from('["Claim.Approve"]') };
    const refused = run(['convert', 'acme.zip', fresh(), '--allow-list', 'bad.json'], bad);
    expect(refused.code).toBe(1);
    expect(refused.err).toContain('an allow-list is { "operations": [ <operation id>, ... ] }');
    expect(run(['convert', 'acme.zip', fresh(), '--allow-list'], files).code).toBe(2);
  });

  it('refuses to convert into a directory that already holds something', () => {
    const out = fresh();
    expect(run(['convert', 'acme.zip', out], files).code).toBe(0);
    const again = run(['convert', 'acme.zip', out], files);
    expect(again.code).toBe(1);
    expect(again.err).toContain('is not an empty directory');
  });

  it('breaks a copy on purpose, and the harness then fails, saying why', () => {
    const good = fresh();
    const broken = fresh();
    run(['convert', 'acme.zip', good], files);
    const mutated = run(['mutate', good, 'wrong-primary-token', broken], files);
    expect(mutated.code).toBe(0);
    expect(mutated.out).toContain(
      'wrong-primary-token: moved the primary colour, #00796b, from --mat-sys-primary to --mat-sys-secondary',
    );
    expect(mutated.out).toContain('check 8 must now fail');

    const checked = run(['check', 'acme.zip', broken], files);
    expect(checked.code).toBe(1);
    expect(checked.out).toMatch(/ 8 {2}Theme +FAIL/);
    expect(checked.out).toContain(
      '- acme: --mat-sys-primary is not set, though --nuxeo-primary-color sets it to #00796b',
    );
    expect(checked.out).toContain('  - check 8 failed');
    // The original is untouched.
    expect(run(['check', 'acme.zip', good], files).code).toBe(0);
  });

  it('lists the mutations, and refuses one it does not know', () => {
    const listed = run(['mutate', '--list']);
    expect(listed.code).toBe(0);
    expect(listed.out).toMatch(
      /^drop-translation +check 4 +Drop one translation from one language$/m,
    );
    const unknown = run(['mutate', fresh(), 'scramble', fresh()]);
    expect(unknown.code).toBe(2);
    expect(unknown.err).toContain('scramble is not a mutation');
  });

  it('writes the harness result as JSON with --json', () => {
    const out = fresh();
    run(['convert', 'acme.zip', out], files);
    const checked = run(['check', 'acme.zip', out, '--json'], files);
    const parsed = JSON.parse(checked.out);
    expect(parsed.ready).toBe(false);
    expect(parsed.checks.map((check: { status: string }) => check.status)).toEqual([
      'pass',
      'pass',
      'partial',
      'pass',
      'partial',
      'partial',
      'partial',
      'pass',
      'not run',
      'pass',
    ]);
  });

  it('exits 1 when the conversion cannot be read', () => {
    const empty = fresh();
    mkdirSync(empty, { recursive: true });
    const checked = run(['check', 'acme.zip', empty], files);
    expect(checked.code).toBe(1);
    expect(checked.err).toContain('holds no report.json');
  });
});

describe('studio-migration decisions and report', () => {
  const files = {
    'acme.zip': syntheticPackage(),
    'allow.json': Buffer.from(JSON.stringify({ operations: ['Claim.Approve'] })),
  };
  const converted = (): string => {
    const out = join(mkdtempSync(join(tmpdir(), 'studio-cli-')), 'conversion');
    run(['convert', 'acme.zip', out, '--allow-list', 'allow.json'], files);
    return out;
  };
  /** Fills in every decision of the conversion's decisions.json. */
  const fill = (directory: string): void => {
    const path = join(directory, 'decisions.json');
    const file = JSON.parse(readFileSync(path, 'utf8'));
    for (const item of file.decisions) {
      item.owner = 'Migration lead';
      item.decision = item.outcome === 'proposed' ? 'accept' : 'Rebuilt by hand';
      if (item.outcome === 'proposed') item.reason = 'The host has the function it calls';
    }
    writeFileSync(path, JSON.stringify(file));
  };

  it('writes decisions.json beside the report, for a person to fill in, and never over one', () => {
    const out = converted();
    const written = run(['decisions', 'acme.zip', out], files);
    expect(written).toMatchObject({ code: 0, err: '' });
    expect(written.out).toBe(
      `Wrote ${join(out, 'decisions.json')}: 14 reported items and 1 proposal, 15 of them still to fill in\n`,
    );
    const file = JSON.parse(readFileSync(join(out, 'decisions.json'), 'utf8'));
    expect(file.decisions).toHaveLength(15);
    expect(run(['check', 'acme.zip', out], files).out).toContain(
      '  - 14 reported items have no owner',
    );

    fill(out);
    const again = run(['decisions', 'acme.zip', out], files);
    expect(again.code).toBe(1);
    expect(again.err).toBe(`${join(out, 'decisions.json')} exists, and is never written over\n`);
    expect(JSON.parse(readFileSync(join(out, 'decisions.json'), 'utf8')).decisions[0].owner).toBe(
      'Migration lead',
    );
    const checked = run(['check', 'acme.zip', out, '--allow-list', 'allow.json'], files);
    expect(checked.out).toContain('Verdict: not ready');
    expect(checked.out).not.toMatch(/reported items? ha/);
    // The proposal it accepts is not written in this conversion, made before it was decided: the
    // checks hold the conversion to what it records, and pass, and readiness says to convert again.
    expect(checked.code).toBe(0);
    expect(checked.out).toContain(
      '  - the conversion was made with 1 of its proposals decided otherwise than decisions.json decides them now',
    );
  });

  it('carries the decisions of an earlier conversion that still hold, and says which do not', () => {
    const earlier = converted();
    run(['decisions', 'acme.zip', earlier], files);
    fill(earlier);
    const old = JSON.parse(readFileSync(join(earlier, 'decisions.json'), 'utf8'));
    old.decisions[0].note = 'An earlier reason';
    const out = converted();
    const carried = run(['decisions', 'acme.zip', out, '--from', 'old.json'], {
      ...files,
      'old.json': Buffer.from(JSON.stringify(old)),
    });
    expect(carried.code).toBe(0);
    expect(carried.out).toContain(
      ': 14 reported items and 1 proposal, 1 of them still to fill in\n' +
        '  carried from old.json: 14\n' +
        '  offered for re-confirmation, the earlier decision beside a blank one: 1\n' +
        '  not carried, and still in old.json: 1\n',
    );
    expect(carried.out).toMatch(
      /\n {4}- old\.json: layout-field:.*#3 was made on another reason than the report gives now, so it is offered for re-confirmation, beside it\n$/,
    );
    // Offered beside a blank decision, with the earlier one and what it was made on.
    const offered = JSON.parse(readFileSync(join(out, 'decisions.json'), 'utf8')).decisions[0];
    expect(offered).toMatchObject({
      owner: '',
      decision: '',
      earlier: {
        owner: 'Migration lead',
        decision: 'Rebuilt by hand',
        madeOn: { note: 'An earlier reason' },
        changed: ['reason'],
      },
    });
    expect(run(['check', 'acme.zip', out], files).out).toContain(
      '  - 1 reported item has no owner',
    );

    const missing = run(['decisions', 'acme.zip', converted(), '--from', 'missing.json'], files);
    expect(missing.code).toBe(1);
    expect(missing.err).toMatch(/^missing\.json: ENOENT/);
    const other = run(['decisions', 'acme.zip', converted(), '--from', 'other.json'], {
      ...files,
      'other.json': Buffer.from(
        JSON.stringify({ ...old, package: { name: 'Other', version: '1' } }),
      ),
    });
    expect(other.code).toBe(1);
    expect(other.err).toMatch(
      /^other\.json is for Other 1, bundle none, and the package given is Acme-Claims 1\.0\.0, bundle [0-9a-f]{12}/,
    );
    expect(run(['decisions', 'acme.zip'], files).code).toBe(2);
    expect(run(['decisions', 'acme.zip', out, '--from'], files).code).toBe(2);
  });

  it('prints the report, and exits 0 whatever it says', () => {
    const out = converted();
    run(['decisions', 'acme.zip', out], files);
    const printed = run(['report', 'acme.zip', out, '--allow-list', 'allow.json'], files);
    expect(printed.code).toBe(0);
    expect(printed.out).toMatch(/^Migration report: Acme-Claims 1\.0\.0\n/);
    expect(printed.out).toContain('Decisions needed: 14 reported items, 0 of them decided');
    expect(printed.out).toMatch(
      /\nCoverage: 100%, 65 of the package's 65 constructs in the report\n/,
    );

    const none = { ...files, 'none.json': Buffer.from('{"operations": []}') };
    const failing = run(['report', 'acme.zip', out, '--allow-list', 'none.json'], none);
    expect(failing.code).toBe(0);
    expect(failing.out).toMatch(/\n {2}10 {2}Package +FAIL\n/);

    const json = JSON.parse(run(['report', 'acme.zip', out, '--json'], files).out);
    expect(json.coverage).toEqual({ accounted: 65, constructs: 65, percent: 100 });
    expect(json.reported).toHaveLength(14);
    expect(run(['report', 'acme.zip'], files).code).toBe(2);
  });

  it('lists the controls of the decisions, and applies one to a copy, which the verdict names', () => {
    expect(run(['mutate', '--list']).out).toMatch(
      /^drop-owner +decisions +Take the owner off the decision of a reported item$/m,
    );
    const out = converted();
    const broken = join(mkdtempSync(join(tmpdir(), 'studio-cli-')), 'broken');
    const nothing = run(['mutate', out, 'drop-owner', broken], files);
    expect(nothing.code).toBe(1);
    expect(nothing.err).toMatch(/^the conversion has no decisions\.json to break/);

    run(['decisions', 'acme.zip', out], files);
    fill(out);
    const mutated = run(['mutate', out, 'drop-owner', broken], files);
    expect(mutated.code).toBe(0);
    expect(mutated.out).toMatch(
      /^drop-owner: took the owner off layout-field:.*#3\. Written to .*; what stands in the way of readiness must now show it\.\n$/,
    );
    expect(run(['check', 'acme.zip', broken], files).out).toContain(
      '  - 1 reported item has no owner',
    );
    expect(run(['check', 'acme.zip', out], files).out).not.toMatch(/reported items? ha/);
  });
});
